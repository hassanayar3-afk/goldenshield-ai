#!/usr/bin/env python3
"""Merge saqr.env.template defaults with existing saqr/.env (keeps non-empty secrets)."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "saqr.env.template"
ENV_PATHS = [ROOT / "saqr" / ".env", ROOT / "saqr" / "saqr.env"]

GROUPS = [
    [
        "SAQR_MODE",
        "SAQR_REQUIRE_INTEGRATED_DEMO",
        "SAQR_ENABLE_TRADING",
        "SAQR_ENABLE_LIVE_ACK",
        "SAQR_INITIAL_BALANCE_USD",
        "SAQR_SYMBOL",
        "SAQR_HOLD_CONSOLE",
    ],
    [
        "BINANCE_TESTNET",
        "BINANCE_REST_URL",
        "BINANCE_WS_URL",
        "BINANCE_MARKET_REST_URL",
        "BINANCE_MARKET_WS_URL",
        "BINANCE_SPOT_WEB_URL",
        "BINANCE_API_KEY",
        "BINANCE_API_SECRET",
        "BINANCE_RECV_WINDOW",
    ],
    [
        "TELEGRAM_BOT_TOKEN",
        "TELEGRAM_CHAT_ID",
        "TELEGRAM_SECONDARY_BOT_TOKEN",
        "SAQR_TELEGRAM_BRIDGE",
        "SAQR_TELEGRAM_CONTROL_PANEL",
        "SAQR_SIGNAL_INTERVAL_SECS",
    ],
    [
        "SAQR_WEB_ENABLED",
        "SAQR_WEB_BIND_HOST",
        "SAQR_WEB_BIND_PORT",
        "SAQR_PUBLIC_DASHBOARD_URL",
    ],
    [
        "SAQR_INTEGRATION_INTERVAL_SECS",
        "SAQR_WAL_PATH",
        "SAQR_WS_RECONNECT_SECS",
        "LOG_LEVEL",
        "RUST_LOG",
    ],
    [
        "CLOUD_SERVER_HOST",
        "CLOUD_SERVER_PORT",
        "CLOUD_SERVER_SSH_USER",
        "CLOUD_SERVER_PASSWORD",
    ],
]


def parse_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.is_file():
        return out
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        s = line.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        k, v = s.split("=", 1)
        out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def main() -> int:
    template = parse_env(TEMPLATE)
    local = parse_env(ENV_PATHS[0])
    merged = dict(template)
    for k, v in local.items():
        if v:
            merged[k] = v
    if merged.get("BINANCE_REST_URL") and not merged.get("BINANCE_MARKET_REST_URL"):
        merged["BINANCE_MARKET_REST_URL"] = merged["BINANCE_REST_URL"]
    if not merged.get("BINANCE_MARKET_WS_URL"):
        merged["BINANCE_MARKET_WS_URL"] = "wss://stream.binance.com:9443"
    merged.setdefault("SAQR_HOLD_CONSOLE", "1")
    merged.setdefault("TELEGRAM_SECONDARY_BOT_TOKEN", "")

    header = (
        "# SAQR ENGINE v6.2.3 — FULL RUN CONFIG\n"
        "# Generated by scripts/prepare_saqr_runtime_env.py\n"
    )
    lines = [header]
    seen: set[str] = set()
    for group in GROUPS:
        for key in group:
            if key in merged:
                lines.append(f"{key}={merged[key]}")
                seen.add(key)
    for key in sorted(merged):
        if key not in seen:
            lines.append(f"{key}={merged[key]}")
    text = "\n".join(lines) + "\n"
    for p in ENV_PATHS:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"Wrote {p} ({len(merged)} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
